CREATE TABLE clientes (
    codigo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(100) NOT NULL,
    cpf varchar(11) NOT NULL UNIQUE,
    email text,
    datanascimento timestamp with time zone NOT NULL
);

CREATE TABLE dividas (
    codigo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clientecodigo integer NOT NULL REFERENCES clientes(codigo) ON DELETE CASCADE,
    valor numeric(12,2) NOT NULL CHECK (valor > 0),
    paga boolean NOT NULL DEFAULT false,
    datacriacao timestamp with time zone NOT NULL,
    datapagamento timestamp with time zone,
    CHECK ((paga = false AND datapagamento IS NULL) OR
           (paga = true AND datapagamento IS NOT NULL AND datapagamento >= datacriacao))
);

CREATE UNIQUE INDEX uma_divida_em_aberto
    ON dividas(clientecodigo) WHERE paga = false;
